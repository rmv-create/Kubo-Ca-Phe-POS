/// Turns the outline data above into a `Path`.
abstract final class KuboRoofPath {
  /// Parses SVG-style outline data.
  ///
  /// Deliberately narrow: it understands absolute `M`, `L`, `C` and `Z`, which
  /// is the whole vocabulary the tracer emits. Anything else is a sign the data
  /// was regenerated with different settings, and throws rather than silently
  /// drawing a wrong shape.
  static Path parse(String data) {
    final Path path = Path()..fillType = PathFillType.evenOdd;
    int i = 0;

    double number() {
      while (i < data.length && (data[i] == ' ' || data[i] == ',')) {
        i++;
      }
      final int start = i;
      if (i < data.length && (data[i] == '-' || data[i] == '+')) {
        i++;
      }
      const int zero = 0x30, nine = 0x39, dot = 0x2e;
      while (i < data.length) {
        final int c = data.codeUnitAt(i);
        if ((c >= zero && c <= nine) || c == dot) {
          i++;
        } else {
          break;
        }
      }
      if (i == start) {
        throw FormatException(
          'Expected a number in roof outline data',
          data,
          i,
        );
      }
      return double.parse(data.substring(start, i));
    }

    while (i < data.length) {
      final String command = data[i++];
      switch (command) {
        case 'M':
          path.moveTo(number(), number());
        case 'L':
          path.lineTo(number(), number());
        case 'C':
          path.cubicTo(
            number(),
            number(),
            number(),
            number(),
            number(),
            number(),
          );
        case 'Z':
          path.close();
        case ' ':
          break;
        default:
          throw FormatException(
            'Unsupported command "$command" in roof outline data',
            data,
            i - 1,
          );
      }
    }
    return path;
  }
}
